#include <stdio.h>
int main()
{
float f;
printf("Enter the Fahrenheit Temparature");
scanf("%f",&f);
float t1=(5*f-160)/9;
printf("%.2f is the Temparature\n",t1);

float b;
printf("Enter the Celsius Temparature");
scanf("%f",&b);
float t2=(9*b+160)/5;
 printf("%.2f is the Temparature\n",t2);

 return 0;





}
